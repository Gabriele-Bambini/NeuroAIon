def _strategy_table(state: ReviewState) -> str:
    rows = ["| Database | Query | Rationale |", "|----------|-------|-----------|"]
    for q in state.strategy.queries:
        rows.append(f"| {q.source} | `{q.query}` | {q.rationale} |")
    return "\n".join(rows)


def _characteristics_table(state: ReviewState) -> str:
    rows = ["| Study | Design | n | Population | Intervention | Comparator | RoB |",
            "|-------|--------|---|------------|--------------|------------|-----|"]
    rob = {r.uid: r.overall for r in state.rob}
    for ex in state.extractions:
        rows.append(
            f"| {ex.study_label} | {ex.design or '—'} | {ex.sample_size or '—'} | "
            f"{(ex.population or '—')[:40]} | {(ex.intervention or '—')[:30]} | "
            f"{(ex.comparator or '—')[:25]} | {rob.get(ex.uid, '—')} |"
        )
    return "\n".join(rows)


def _rob_table(state: ReviewState) -> str:
    if not state.rob:
        return "_No included studies appraised._"
    domains = [d.name for d in state.rob[0].domains]
    header = "| Study | " + " | ".join(domains) + " | Overall |"
    sep = "|" + "---|" * (len(domains) + 2)
    rows = [header, sep]
    for a in state.rob:
        jud = {d.name: d.judgement for d in a.domains}
        rows.append("| " + a.study_label + " | " +
                    " | ".join(jud.get(d, "—") for d in domains) + f" | {a.overall} |")
    return "\n".join(rows)


def _forest_table(state: ReviewState) -> str:
    meta = state.synthesis.meta_analysis
    if not meta or not meta.forest:
        return "_Meta-analysis not performed._"
    rows = [f"| Study | {meta.measure} | 95% CI | Weight % |",
            "|-------|------|--------|----------|"]
    for f in meta.forest:
        rows.append(f"| {f['study']} | {f['estimate']} | "
                    f"[{f['ci_lower']}, {f['ci_upper']}] | {f['weight_pct']} |")
    rows.append(f"| **Pooled ({meta.model})** | **{meta.pooled_estimate}** | "
                f"**[{meta.ci_lower}, {meta.ci_upper}]** | 100 |")
    return "\n".join(rows)


def _pub_bias_line(state: ReviewState) -> str:
    meta = state.synthesis.meta_analysis
    if not meta or meta.eggers_p is None:
        return ("Not formally tested (fewer than three studies with usable "
                "variances); a funnel plot is provided in the LaTeX paper where applicable.")
    asym = "evidence of" if meta.eggers_p < 0.10 else "no strong evidence of"
    power = " (under-powered, k<10)" if (meta.eggers_k or 0) < 10 else ""
    return (f"Egger's test: {asym} funnel asymmetry "
            f"(intercept={meta.eggers_intercept}, p={meta.eggers_p}, k={meta.eggers_k}){power}. "
            f"See the funnel plot in `paper.tex`.")


def _references(state: ReviewState) -> str:
    included = {u for u in state.included_studies}
    by_uid = {r.uid: r for r in state.unique_records}
    lines = []
    for i, uid in enumerate(state.included_studies, 1):
        r = by_uid.get(uid)
        if r:
            doi = f" https://doi.org/{r.doi}" if r.doi else ""
            lines.append(f"{i}. {r.citation()}.{doi}")
    return "\n".join(lines) or "_No included studies._"


