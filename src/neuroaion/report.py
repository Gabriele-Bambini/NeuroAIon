def write_artifacts(out_dir: Path, state: ReviewState, prose: dict[str, str]) -> Path:
    """Write the manuscript and all machine-readable artefacts; return report path."""
    out_dir.mkdir(parents=True, exist_ok=True)

    report_path = out_dir / "report.md"
    report_path.write_text(build_markdown(state, prose), encoding="utf-8")

    # Browser-friendly self-contained HTML (inline SVG figures).
    from . import html_report
    (out_dir / "review.html").write_text(
        html_report.build_html(state, prose), encoding="utf-8")

    (out_dir / "state.json").write_text(state.model_dump_json(indent=2), encoding="utf-8")
    (out_dir / "prisma_flow.json").write_text(
        state.prisma.model_dump_json(indent=2), encoding="utf-8")
    (out_dir / "extractions.json").write_text(
        json.dumps([e.model_dump() for e in state.extractions], indent=2), encoding="utf-8")

    # Included studies CSV.
    by_uid = {r.uid: r for r in state.unique_records}
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["uid", "citation", "doi", "source", "year"])
    for uid in state.included_studies:
        r = by_uid.get(uid)
        if r:
            w.writerow([uid, r.citation(), r.doi, r.source, r.year])
    (out_dir / "included_studies.csv").write_text(buf.getvalue(), encoding="utf-8")

    # PROSPERO registration export (PRISMA item 24).
    if state.protocol.prospero_export:
        from . import prospero
        (out_dir / "prospero_registration.md").write_text(
            prospero.build_registration(state), encoding="utf-8")

    return report_path


def write_latex(out_dir: Path, state: ReviewState, prose: dict[str, str]) -> Path:
    """Write the self-contained LaTeX paper and its bibliography. Returns the .tex path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    tex, bib = _latex.build_document(state, prose)
    tex_path = out_dir / "paper.tex"
    tex_path.write_text(tex, encoding="utf-8")
    (out_dir / "references.bib").write_text(bib, encoding="utf-8")
    return tex_path


def compile_pdf(tex_path: Path) -> Path | None:
    """Best-effort PDF compilation if a TeX engine is available; else None."""
    import shutil
    import subprocess

    engine = shutil.which("latexmk") or shutil.which("pdflatex")
    if not engine:
        return None
    cwd = tex_path.parent
    try:
        if engine.endswith("latexmk"):
            cmd = [engine, "-pdf", "-interaction=nonstopmode", "-halt-on-error", tex_path.name]
            subprocess.run(cmd, cwd=cwd, capture_output=True, timeout=300)
        else:
            for _ in range(3):  # pdflatex + bibtex + pdflatex + pdflatex
                subprocess.run([engine, "-interaction=nonstopmode", "-halt-on-error",
                                tex_path.name], cwd=cwd, capture_output=True, timeout=300)
                subprocess.run(["bibtex", tex_path.stem], cwd=cwd, capture_output=True, timeout=120)
    except Exception:  # noqa: BLE001
        return None
    pdf = tex_path.with_suffix(".pdf")
    return pdf if pdf.exists() else None
